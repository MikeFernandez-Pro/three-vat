// `pnpm import-colliders [in.glb]`: the colliders modelled in Blender, every
// object named `collider…` in the file (default exports/sewers2.3.glb), read
// into the map as outlines on the ground: each one's vertices put through its
// transform, dropped to the ground and hulled, so a turned box or a cylinder
// comes out as the polygon it stands on. Written to src/sewers.colliders.ts,
// which sewers.ts lays as solid masses (and sewerplay.ts stands the huge
// door's ones up and takes them down as it opens). Nothing in the file is
// drawn: the 3D page hides them.
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Matrix4, Quaternion, Vector3 } from 'three'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const input = resolve(root, process.argv[2] ?? 'exports/sewers2.3.glb')
const output = resolve(root, 'src/sewers.colliders.ts')

const file = await readFile(input)
if (file.readUInt32LE(0) !== 0x46546c67) throw new Error(`${input} is not a GLB`)
const jsonLength = file.readUInt32LE(12)
const gltf = JSON.parse(file.subarray(20, 20 + jsonLength).toString())
const binStart = 20 + jsonLength + 8
const bin = file.subarray(binStart, binStart + file.readUInt32LE(20 + jsonLength))

/** An accessor's values, floats only, `size` a row. */
function floats(accessorIndex) {
  const accessor = gltf.accessors[accessorIndex]
  if (accessor.componentType !== 5126) throw new Error(`accessor ${accessorIndex}: only float positions are read`)
  const size = { SCALAR: 1, VEC2: 2, VEC3: 3, VEC4: 4 }[accessor.type]
  const view = gltf.bufferViews[accessor.bufferView]
  const stride = view.byteStride ?? size * 4
  const start = (view.byteOffset ?? 0) + (accessor.byteOffset ?? 0)
  const rows = []
  for (let k = 0; k < accessor.count; k++) {
    const at = start + k * stride
    const row = []
    for (let c = 0; c < size; c++) row.push(bin.readFloatLE(at + c * 4))
    rows.push(row)
  }
  return rows
}

const parents = new Array(gltf.nodes.length).fill(-1)
gltf.nodes.forEach((node, k) => (node.children ?? []).forEach((child) => (parents[child] = k)))
const local = (node) =>
  new Matrix4().compose(
    new Vector3(...(node.translation ?? [0, 0, 0])),
    new Quaternion(...(node.rotation ?? [0, 0, 0, 1])),
    new Vector3(...(node.scale ?? [1, 1, 1])),
  )
const world = (k) => {
  const own = local(gltf.nodes[k])
  return parents[k] < 0 ? own : world(parents[k]).multiply(own)
}

/** The convex hull of ground points, counter-clockwise seen from above (x right, z down the page), Andrew's monotone chain. */
function hull(points) {
  const sorted = [...new Map(points.map((p) => [`${p.x},${p.z}`, p])).values()].sort((a, b) => a.x - b.x || a.z - b.z)
  if (sorted.length < 3) return sorted
  const cross = (o, a, b) => (a.x - o.x) * (b.z - o.z) - (a.z - o.z) * (b.x - o.x)
  const lower = []
  for (const p of sorted) {
    while (lower.length >= 2 && cross(lower[lower.length - 2], lower[lower.length - 1], p) <= 0) lower.pop()
    lower.push(p)
  }
  const upper = []
  for (const p of [...sorted].reverse()) {
    while (upper.length >= 2 && cross(upper[upper.length - 2], upper[upper.length - 1], p) <= 0) upper.pop()
    upper.push(p)
  }
  return [...lower.slice(0, -1), ...upper.slice(0, -1)]
}

const round = (v) => Math.round(v * 1000) / 1000
const colliders = []
gltf.nodes.forEach((node, k) => {
  if (!/^collider/i.test(node.name ?? '') || node.mesh === undefined) return
  const matrix = world(k)
  const points = []
  for (const primitive of gltf.meshes[node.mesh].primitives) {
    for (const [x, y, z] of floats(primitive.attributes.POSITION)) {
      const p = new Vector3(x, y, z).applyMatrix4(matrix)
      points.push({ x: round(p.x), z: round(p.z) })
    }
  }
  colliders.push({ name: node.name, outline: hull(points) })
})
colliders.sort((a, b) => a.name.localeCompare(b.name))

const lines = [
  '// GENERATED by tools/import-colliders.mjs (`pnpm import-colliders`) from the Blender file: do not edit.',
  "// The colliders modelled there, each as the outline it stands on, m, counter-clockwise seen from above.",
  "import type { Point } from './sewers'",
  '',
  'export interface Collider {',
  '  name: string',
  '  outline: Point[]',
  '}',
  '',
  'export const COLLIDERS: readonly Collider[] = [',
  ...colliders.map((c) => `  { name: '${c.name}', outline: [${c.outline.map((p) => `{ x: ${p.x}, z: ${p.z} }`).join(', ')}] },`),
  ']',
  '',
]
await writeFile(output, lines.join('\n'))
console.log(`${output}: ${colliders.length} colliders from ${input}`)
