/** The theme `name`, or none for no name; an unknown name throws, listing the themes. */
export function gooseThemeOf(name: string | null): GooseTheme | undefined {
  if (name === null) return undefined
  const theme = GOOSE_THEMES[name]
  if (!theme) throw new Error(`no theme "${name}": ${Object.keys(GOOSE_THEMES).join(', ')}`)
  return theme
}

/** `source` laid into `target` in place, object by object, so the panel's controls stay bound; arrays and values replaced. */
export function layInto(target: object, source: object): void {
  for (const [key, value] of Object.entries(source)) {
    const into = (target as Record<string, unknown>)[key]
    if (value && typeof value === 'object' && !Array.isArray(value) && into && typeof into === 'object') layInto(into, value)
    else (target as Record<string, unknown>)[key] = value
  }
}
