// the rats' fur, highlight, rim and eyes, the flame, the floor's tint, the ink
// in the creases. The goose and her goslings keep their own colours: only her
// rim and highlight follow the light.
import type { Look } from './panel'
import type { ShellLook } from './shell'

type DeepPartial<T> = { [K in keyof T]?: T[K] extends readonly unknown[] ? T[K] : T[K] extends object ? DeepPartial<T[K]> : T[K] }

export interface GooseTheme {
  title: string
  note: string
  look: DeepPartial<Look>
  /** The rats' eyes, which their trails take. */
  eyes?: number
  /** The fires' lamps, the spawn pit's among them. */
  fireLamp?: number
  /** The doors' (the road's arches') toon shell, its own values over the floor's. */
  doors?: Partial<ShellLook>
  /** The road's broken walls' toon shell, its own values over the doors'. */
  walls?: Partial<ShellLook>
}

